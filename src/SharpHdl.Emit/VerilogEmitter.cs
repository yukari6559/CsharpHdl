using System.Globalization;
using System.Text;
using SharpHdl.Core.Exceptions;
using SharpHdl.Core.Model;

namespace SharpHdl.Emit;

/// <summary>
/// Verilog emitter の入口プレースホルダ。実装は docs/verilog-emit-spec.md に従う。
/// </summary>
public static class VerilogEmitter
{
	public static string EmitPlaceholder(string moduleName)
	{
		return $"// Generated by CsharpHdl (stub)\nmodule {moduleName};\nendmodule\n";
	}

	public static string Emitter(Module top, string topName)
	{
		List<InstanceStmt> instanceStmts = [];

		return EmitOneModule(top, topName, instanceStmts, true);
	}

	public static string EmitExpr(Expr expr)
	{

		if (expr is Signal signal)
		{
			return signal.Name;
		}
		else if (expr is OpExpr opExpr)
		{
			return EmitExpr(opExpr.Left) + " " + opExpr.Op.ToCustomString() + " " + EmitExpr(opExpr.Right);
		}
		else if (expr is SliceExpr sliceExpr)
		{
			return EmitExpr(sliceExpr.Expr) + $"[{sliceExpr.MSB}:{sliceExpr.LSB}]";
		}
		else if (expr is ConcatExpr concatExpr)
		{
			string s = "{";
			for (int i = 0; i < concatExpr.Exprs.Length; i++)
			{
				if (i == concatExpr.Exprs.Length - 1)
				{
					s += $"{EmitExpr(concatExpr.Exprs[i])}";
				}
				else
				{
					s += $"{EmitExpr(concatExpr.Exprs[i])}, ";
				}
			}
			s += "}";
			return s;
		}
		else if (expr is SignExtendExpr signExtendExpr)
		{
			if (signExtendExpr.GetWidth() - signExtendExpr.Expr.GetWidth() == 0)
			{
				return EmitExpr(signExtendExpr.Expr);
			}
			else
			{
				string s = "{{" + $"{signExtendExpr.GetWidth() - signExtendExpr.Expr.GetWidth()}{{" + $"{EmitExpr(signExtendExpr.Expr)}[{signExtendExpr.Expr.GetWidth() - 1}]" + "}}, " + $"{EmitExpr(signExtendExpr.Expr)}" + "}";
				return s;
			}
		}
		else if (expr is ZeroExtendExpr zeroExtendExpr)
		{
			if (zeroExtendExpr.GetWidth() - zeroExtendExpr.Expr.GetWidth() == 0)
			{
				return EmitExpr(zeroExtendExpr.Expr);
			}
			else
			{
				string s = "{{" + $"{zeroExtendExpr.GetWidth() - zeroExtendExpr.Expr.GetWidth()}" + "{1'b0}}, " + $"{EmitExpr(zeroExtendExpr.Expr)}}}";
				return s;
			}
		}
		else if (expr is ConstExpr constExpr)
		{
			ulong masked = constExpr.Width != 64
				? constExpr.Value & ((1UL << (int)constExpr.Width) - 1)
				: constExpr.Width == 64 ? constExpr.Value : throw new WidthMismatchException();
			string s = $"{constExpr.Width}'d{masked}";
			return s;
		}
		else
		{
			throw new EmitException();
		}
	}

	public static HashSet<Signal> CollectRegOuts(List<Stmt> stmts, HashSet<Signal> regOuts)
	{
		foreach (Stmt item in stmts)
		{
			if (item is SeqBlockStmt seq)
			{
				foreach (Stmt body in seq.Body)
				{
					if (body is SeqAssignStmt sa)
					{
						_ = regOuts.Add(sa.Signal);
					}
				}
			}
			if (item is MemStmt memStmt)
			{
				_ = regOuts.Add(memStmt.Rdata);
			}
			if (item is MemWstrbStmt memWstrbStmt)
			{
				_ = regOuts.Add(memWstrbStmt.Rdata);
			}
			if (item is IfStmt ifStmt)
			{
				foreach (Stmt thenItem in ifStmt.Then)
				{
					if (thenItem is AssignStmt assignStmt)
					{
						_ = regOuts.Add(assignStmt.Signal);
					}
				}
				if (ifStmt.Else != null)
				{
					foreach (Stmt elseItem in ifStmt.Else)
					{
						if (elseItem is AssignStmt assignStmt)
						{
							_ = regOuts.Add(assignStmt.Signal);
						}
					}
				}
			}
		}
		return regOuts;
	}

	public static void WireDefine(List<Signal> signals, StringBuilder verilogsb, HashSet<Signal> regOuts)
	{
		for (int i = 0; i < signals.Count; i++)
		{
			Signal item = signals[i];
			if (item.Width == 1)
			{
				if (item.Direction == SignalDirection.Input)
				{
					_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\tinput wire {item.Name}");
				}
				else if (regOuts.Contains(item))
				{
					_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\toutput reg [{item.Width - 1}:0] {item.Name}");
				}
				else if (item.Direction == SignalDirection.Output)
				{
					_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\toutput wire {item.Name}");
				}
			}
			else if (item.Direction == SignalDirection.Input)
			{
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\tinput wire [{item.Width - 1}:0] {item.Name}");
			}
			else if (regOuts.Contains(item))
			{
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\toutput reg [{item.Width - 1}:0] {item.Name}");
			}
			else if (item.Direction == SignalDirection.Output)
			{
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\toutput wire [{item.Width - 1}:0] {item.Name}");
			}

			_ = i + 1 != signals.Count ? verilogsb.Append(",\n") : verilogsb.Append('\n');
		}
		_ = verilogsb.Append(");\n");
	}

	public static void EmitModuleBody(List<Stmt> stmts, StringBuilder verilogsb)
	{
		foreach (Stmt item in stmts)
		{
			if (item is MemStmt memStmt)
			{
				string memName = $"mem_{memStmt.Rdata.Name}";
				if (!string.IsNullOrEmpty(memStmt.Name))
				{
					memName = memStmt.Name;
				}
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"reg [{memStmt.Width - 1}:0] {memName} [0:{memStmt.Depth - 1}];\n");
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"always @(posedge {memStmt.Clk.Name}) begin\n");
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\tif ({memStmt.We.Name}) {memName}[{memStmt.Addr.Name}] <= {memStmt.Wdata.Name};\n");
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\t{memStmt.Rdata.Name} <= {memName}[{memStmt.Addr.Name}];\n");
				_ = verilogsb.Append($"end\n");
			}
			if (item is Mem2R1WStmt mem2R1WStmt)
			{
				string memName = $"mem_{mem2R1WStmt.Rdata0.Name}";
				if (!string.IsNullOrEmpty(mem2R1WStmt.Name))
				{
					memName = mem2R1WStmt.Name;
				}
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"reg [{mem2R1WStmt.Width - 1}:0] {memName} [0:{mem2R1WStmt.Depth - 1}];\n");
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"always @(posedge {mem2R1WStmt.Clk.Name}) begin\n");
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\tif ({mem2R1WStmt.We.Name}) {memName}[{mem2R1WStmt.Waddr.Name}] <= {mem2R1WStmt.Wdata.Name};\n");
				_ = verilogsb.Append("end\n");
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"assign {mem2R1WStmt.Rdata0.Name} = {memName}[{mem2R1WStmt.Raddr0.Name}];\n");
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"assign {mem2R1WStmt.Rdata1.Name} = {memName}[{mem2R1WStmt.Raddr1.Name}];\n");
			}
			if (item is MemWstrbStmt memWstrbStmt)
			{
				string memName = $"mem_{memWstrbStmt.Rdata.Name}";
				if (!string.IsNullOrEmpty(memWstrbStmt.Name))
				{
					memName = memWstrbStmt.Name;
				}
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"reg [{memWstrbStmt.Width - 1}:0] {memName} [0:{memWstrbStmt.Depth - 1}];\n");
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"always @(posedge {memWstrbStmt.Clk.Name}) begin\n");
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\tif ({memWstrbStmt.We.Name}) begin\n");
				uint memLSB = 0;
				uint memMSB = 7;
				for (int i = 0; i < memWstrbStmt.Width / 8; i++)
				{
					_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\t\tif ({memWstrbStmt.Wstrb.Name}[{i}]) {memName}[{memWstrbStmt.Addr.Name}][{memMSB}:{memLSB}] <= {memWstrbStmt.Wdata.Name}[{memMSB}:{memLSB}];\n");
					memLSB += 8;
					memMSB += 8;
				}
				_ = verilogsb.Append("\tend\n");
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\t{memWstrbStmt.Rdata.Name} <= {memName}[{memWstrbStmt.Addr.Name}];\n");
				_ = verilogsb.Append($"end\n");
			}
			if (item is AssignStmt)
			{
				AssignStmt assignStmt = (AssignStmt)item;
				Expr expr = assignStmt.Expr;
				string s = EmitExpr(expr);
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\tassign {assignStmt.Signal.Name} = {s};\n");
			}
			if (item is SeqBlockStmt seqBlock)
			{
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\talways @(posedge {seqBlock.Clk.Name}) begin\n");
				foreach (Stmt bodyItem in seqBlock.Body)
				{
					if (bodyItem is SeqAssignStmt seqAssign)
					{
						_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\t\tif ({seqBlock.Reset.Name}) begin\n");
						_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\t\t\t{seqAssign.Signal.Name} <= {seqAssign.Signal.Width}'d{seqAssign.ResetValue};\n");
						_ = verilogsb.Append("\t\tend else begin\n");
						_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\t\t\t{seqAssign.Signal.Name} <= {EmitExpr(seqAssign.Expr)};\n");
						_ = verilogsb.Append("\t\tend\n");
					}
				}
				_ = verilogsb.Append("\tend\n");
			}
			if (item is SwitchStmt switchStmt)
			{
				Signal? beforeSignal = null;
				AssignStmt assignStmt;
				if (switchStmt.Cases.Count == 0)
				{
					throw new EmitException("Switch emit: Cases must not be empty.");
				}

				for (int i = 0; i < switchStmt.Cases.Count; i++)
				{
					if (switchStmt.Cases[i].Stmts.Count != 1)
					{
						throw new EmitException($"Switch emit: case {i} (value {switchStmt.Cases[i].Value}) must contain exactly one statement, got {switchStmt.Cases[i].Stmts.Count}.");
					}

					if (switchStmt.Cases[i].Stmts[0] is not AssignStmt)
					{
						throw new EmitException($"Switch emit: case {i} (value {switchStmt.Cases[i].Value}) must be a single AssignStmt.");
					}

					assignStmt = (AssignStmt)switchStmt.Cases[i].Stmts[0];
					if (i != 0 && beforeSignal != assignStmt.Signal)
					{
						throw new EmitException($"Switch emit: all cases must assign the same signal (case 0: {beforeSignal!.Name}, case {i}: {assignStmt.Signal.Name}).");
					}
					else if (i == 0)
					{
						_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\tassign {assignStmt.Signal.Name} = ({switchStmt.Signal.Name} == {switchStmt.Signal.Width}'d{switchStmt.Cases[0].Value}) ? ({EmitExpr(assignStmt.Expr)}) :\n");
						beforeSignal = assignStmt.Signal;
						continue;
					}
					else if (i == switchStmt.Cases.Count - 1)
					{
						_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\t\t({EmitExpr(assignStmt.Expr)});\n");
						break;
					}
					_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\t\t({switchStmt.Signal.Name} == {switchStmt.Signal.Width}'d{switchStmt.Cases[i].Value}) ? ({EmitExpr(assignStmt.Expr)}) :\n");
					beforeSignal = assignStmt.Signal;
				}
			}
			if (item is IfStmt ifStmt)
			{
				_ = verilogsb.Append("always @(*) begin\n");
				_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\tif ({EmitExpr(ifStmt.Cond)}) begin\n");
				foreach (Stmt thenItem in ifStmt.Then)
				{
					_ = thenItem is AssignStmt assignStmt
						? verilogsb.Append(CultureInfo.InvariantCulture, $"\t\t{assignStmt.Signal.Name} = {EmitExpr(assignStmt.Expr)};\n")
						: throw new EmitException();
				}
				_ = verilogsb.Append("\tend\n");
				if (ifStmt.Else != null)
				{
					_ = verilogsb.Append("\telse begin\n");
					foreach (Stmt elseItem in ifStmt.Else)
					{
						_ = elseItem is AssignStmt assignStmt
							? verilogsb.Append(CultureInfo.InvariantCulture, $"\t\t{assignStmt.Signal.Name} = {EmitExpr(assignStmt.Expr)};\n")
							: throw new EmitException();
					}
					_ = verilogsb.Append("\tend\n");
				}

				_ = verilogsb.Append("end\n");
			}
		}
	}

	public static void CollectInstances(List<Stmt> stmts, List<InstanceStmt> instanceStmts, StringBuilder verilogsb)
	{
		HashSet<string> emitted = [];
		foreach (Stmt item in stmts)
		{
			if (item is InstanceStmt stmt)
			{
				instanceStmts.Add(stmt);
				if (!emitted.Add(stmt.ChildModule.GetType().Name))
				{
					continue;
				}

				_ = verilogsb.Append(EmitOneModule(stmt.ChildModule, stmt.ChildModule.GetType().Name, [], false));
			}
		}
	}

	public static void EmitInstanceLines(List<InstanceStmt> instanceStmts, StringBuilder verilogsb)
	{
		foreach (InstanceStmt item in instanceStmts)
		{
			_ = verilogsb.Append(CultureInfo.InvariantCulture, $"\t{item.ChildModule.GetType().Name} {item.InstanceName} (\n");
			for (int i = 0; i < item.PortConnections.Count; i++)
			{
				_ = i == item.PortConnections.Count - 1
					? verilogsb.Append(CultureInfo.InvariantCulture, $"\t\t.{item.PortConnections[i].ChildPort.Name}({item.PortConnections[i].ParentSignal.Name})")
					: verilogsb.Append(CultureInfo.InvariantCulture, $"\t\t.{item.PortConnections[i].ChildPort.Name}({item.PortConnections[i].ParentSignal.Name}),");
			}
			_ = verilogsb.Append(");\n");
		}
	}

	public static string EmitOneModule(Module module, string moduleName, List<InstanceStmt> instanceStmts, bool emitHierarchy)
	{
		StringBuilder verilogsb = new();

		List<Signal> signals = [.. module.GetPorts()];
		List<Stmt> stmts = [.. module.GetStmts()];
		HashSet<Signal> regOuts = [];

		if (emitHierarchy)
		{
			CollectInstances(stmts, instanceStmts, verilogsb);
		}

		_ = verilogsb.Append(CultureInfo.InvariantCulture, $"module {moduleName}(\n");
		_ = CollectRegOuts(stmts, regOuts);

		WireDefine(signals, verilogsb, regOuts);

		if (emitHierarchy)
		{
			EmitInstanceLines(instanceStmts, verilogsb);
		}

		EmitModuleBody(stmts, verilogsb);

		_ = verilogsb.Append("endmodule");

		return verilogsb.ToString();
	}
}
